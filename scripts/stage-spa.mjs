import { cp, mkdir, readFile, rm, writeFile } from "node:fs/promises";
import { join } from "node:path";

const root = process.cwd();
const dist = join(root, "artifacts/bookcase-community/dist/public");
await rm(join(root, "public/assets"), { recursive: true, force: true });
await mkdir(join(root, "public/assets"), { recursive: true });
await cp(join(dist, "assets"), join(root, "public/assets"), { recursive: true });
for (const file of ["favicon.svg", "logo.svg", "robots.txt"]) {
  await cp(join(dist, file), join(root, "public", file)).catch(() => {});
}
const html = await readFile(join(dist, "index.html"), "utf8");
await mkdir(join(root, "src/server"), { recursive: true });
await writeFile(
  join(root, "src/server/spa-html.ts"),
  `// Generated by scripts/stage-spa.mjs. Do not edit.\nexport const spaHtml = ${JSON.stringify(html)};\n`,
);
console.log("stage-spa: shell ready");
